"""Pass 7 step 1: character and token noise statistics, train vs test, per country and source.
Samples up to 300k raw records per (split, source, country). Writes docs/noise_audit.md.
Run: python -m src.noise_audit
"""
import re
import warnings

warnings.filterwarnings("ignore", message="This pattern is interpreted as a regular expression")
import unicodedata

import numpy as np
import pandas as pd
import pyarrow.parquet as pq

from src.data import CACHE, ROOT, start_memory_guard

SAMPLE = 300_000
BLOCKS = {"latin_accented": (0x00C0, 0x024F), "devanagari": (0x0900, 0x097F), "bengali": (0x0980, 0x09FF),
          "gurmukhi": (0x0A00, 0x0A7F), "gujarati": (0x0A80, 0x0AFF), "tamil": (0x0B80, 0x0BFF),
          "telugu": (0x0C00, 0x0C7F), "kannada": (0x0C80, 0x0CFF), "malayalam": (0x0D00, 0x0D7F)}
PATTERNS = {  # applied to the raw name (n) or address (a)
    "name: any non-ASCII": ("n", r"[^\x00-\x7f]"),
    "name: digit": ("n", r"\d"),
    "name: URL/domain (www., http, .com/.org/.net/.in/.fr...)": ("n", r"(?i)https?://|www\.|\.(?:com|org|net|in|co\.in|fr|biz|info|us)\b"),
    "name: @ or #": ("n", r"[@#]"),
    "name: trailing 6-12 digit number": ("n", r"(?:^|[\s\-–#])\d{6,12}\s*$"),
    "name: bracketed text": ("n", r"[\(\[\{][^\)\]\}]*[\)\]\}]"),
    "name: empty brackets": ("n", r"[\(\[\{]\s*[\)\]\}]"),
    "name: doubled word": ("n", r"(?i)\b(\w+)\s+\1\b"),
    "name: junk token (N/A, <NULL>, ##, --)": ("n", r"(?i)\bn/a\b|<null>|##|--"),
    "name: all caps (no lowercase letter)": ("n", r"^[^a-z]*[A-Z][^a-z]*$"),
    "addr: any non-ASCII": ("a", r"[^\x00-\x7f]"),
    "addr: junk token (N/A, <NULL>, ##, --)": ("a", r"(?i)\bn/a\b|<null>|##|--"),
    "addr: # before a number": ("a", r"#\s*\d"),
    "addr: empty": ("a", r"^\s*$"),
    "addr: all caps (no lowercase letter)": ("a", r"^[^a-z]*[A-Z][^a-z]*$"),
}


def block_share(s: pd.Series, lo: int, hi: int) -> float:
    rx = re.compile(f"[{chr(lo)}-{chr(hi)}]")
    return s.str.contains(rx).mean()


def accent_latin(s: pd.Series) -> float:
    """Share of strings with a Latin letter carrying a combining mark (é, Ç, à...)."""
    def has(x: str) -> bool:
        return any(unicodedata.combining(c) for c in unicodedata.normalize("NFKD", x)
                   if not c.isascii() or unicodedata.combining(c)) and bool(re.search(r"[À-ɏ]", x))
    return s.map(has).mean()


def stats(df: pd.DataFrame) -> dict:
    n, a = df["business_name"].fillna(""), df["business_address"].fillna("")
    out = {k: (n if col == "n" else a).str.contains(p, regex=True).mean() for k, (col, p) in PATTERNS.items()}
    for b, (lo, hi) in BLOCKS.items():
        out[f"name: {b} script"] = block_share(n, lo, hi)
        out[f"addr: {b} script"] = block_share(a, lo, hi)
    out["name: accented Latin letter"] = accent_latin(n)
    out["addr: accented Latin letter"] = accent_latin(a)
    words = n.str.split()
    out["name: tokens (mean)"] = words.str.len().mean()
    out["name: token length (mean chars)"] = n.str.replace(r"\s+", "", regex=True).str.len().mean() / max(out["name: tokens (mean)"], 1e-9)
    letters = n.str.count(r"[A-Za-z]")
    out["name: uppercase share of letters"] = (n.str.count(r"[A-Z]") / letters.where(letters > 0)).mean()
    return out


def main() -> None:
    start_memory_guard()
    cols = {}
    for split in ("train", "test"):
        for s in ("source1", "source2", "source3"):
            df = pq.read_table(CACHE / f"{split}_{s}.parquet").to_pandas()
            for c, g in df.groupby("country"):
                g = g.sample(min(SAMPLE, len(g)), random_state=42)
                cols[(c, split, s)] = stats(g)
            del df
    t = pd.DataFrame(cols)
    rows = []
    for (c, split, s) in t.columns:
        if split != "test":
            continue
        ref = t[[k for k in t.columns if k[1] == "train" and k[2] == s and (k[0] == c or c not in {x[0] for x in t.columns if x[1] == "train"})]].mean(axis=1)
        rows.append((c, s, t[(c, split, s)], ref))
    lines = ["# Noise audit: train vs test (generated by `python -m src.noise_audit`)", "",
             f"Raw names and addresses, up to {SAMPLE:,} random records per (split, source, country). France has no "
             "training data, so France test is compared with the mean of train India and US for the same source. "
             "Shares are fractions of records. **Flagged** = test at least 1.5x train and at least 0.5 points higher.", ""]
    flagged = []
    for c, s, te, tr in rows:
        lines += [f"## {c}, {s} (test vs {'train ' + c if c in ('India', 'US') else 'train India+US mean'})", "",
                  "| statistic | train | test | ratio |", "|---|---|---|---|"]
        for k in t.index:
            a, b = tr[k], te[k]
            ratio = b / a if a > 0 else (np.inf if b > 0 else 1.0)
            flag = "share" not in k and "mean" not in k and b - a >= 0.005 and ratio >= 1.5
            if flag:
                flagged.append((c, s, k, a, b))
            lines.append(f"| {k} | {a:.4f} | {b:.4f} | {ratio:.2f}{' **flag**' if flag else ''} |")
        lines.append("")
    summary = ["## Noise types more common in test than in train", "",
               "| country | source | statistic | train | test |", "|---|---|---|---|---|"]
    summary += [f"| {c} | {s} | {k} | {a:.4f} | {b:.4f} |" for c, s, k, a, b in flagged]
    coverage = [
        "## Reading the audit and how normalize.py (Pass 7) covers each noise type", "",
        "- **S1 is clean in every split; the noise is in S2/S3.** For India and US, test S2/S3 noise matches train "
        "within a few percent, so test is not noisier than train there. **France is the difference**: accented Latin "
        "letters in 16-28% of France names and addresses (real accents such as 'Merignac' plus injected ones such as "
        "'Comite' with a cedilla), which train never shows in addresses. This is consistent with Pass 5 gaining far "
        "more on the leaderboard (+0.066) than on eval (+0.013): eval has no France.",
        "- Accents (France; also ~5-7% of India/US S2/S3 names): anyascii folding of every non-ASCII character.",
        "- Indic scripts (India S2/S3: 18-28% of names, ~14% of addresses in Devanagari alone; also Bengali, "
        "Gujarati, Gurmukhi, Tamil, Telugu, Kannada, Malayalam): transliteration with anyascii; transliterated legal "
        "forms (praivet/praibhet/piraivet/praivrr, limited/limitet/limirrd/limtid, 'pra li', elelpi) map to "
        "pvt / ltd / pvt ltd / llp.",
        "- URL / domain names (3-4% of S2/S3 names), @ or # (~1%): protocol, www., TLD and leading @/# stripped.",
        "- Trailing 6-12 digit numbers (~0.3%): stripped after a space, - , en dash or #.",
        "- Bracketed text (6-10%): brackets become spaces, content kept (it is usually part of the name); empty "
        "brackets and [..] removed as junk.",
        "- Doubled words (~2.3% of S2/S3 names): consecutive duplicates collapsed.",
        "- Junk tokens (N/A, <NULL>, ##, --): removed from names and addresses (~4.5% of S2/S3 addresses).",
        "- '#' before a number in addresses (5-11%): punctuation becomes a space, so '##19821' -> '19821'.",
        "- Case (uppercase share differs by source): everything is lowercased.",
        "- French legal forms and street words (EURL, SCI, SARL, SAS, SASU, SA, SNC, SCOP; rue/r, av, bd, pl, all, "
        "imp, ch, rte, fbg, sq): Tables 5.3 / 5.4 extended; 'r' -> 'rue' only for French addresses.", ""]
    lines[5:5] = summary + [""] + coverage
    (ROOT / "docs" / "noise_audit.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(summary))


if __name__ == "__main__":
    main()
