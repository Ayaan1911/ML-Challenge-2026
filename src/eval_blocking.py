"""Evaluate blocking on the dev slice and extrapolate to full scale -> docs/blocking_report.md.

Run: python -m src.eval_blocking --ks 3 5 10 --calibrate-k 5 --sample 200000
Each blocking run is a separate process so its runtime and peak memory are measured cleanly.
"""
import argparse
import json
import subprocess
import sys

import pandas as pd

from src.blocking import COSINES, FLAGS
from src.data import CACHE, ROOT, load_truth_df
from src.dev_slice import load_dev
from src.metric import macro_f05
from src.norm_cache import norm_path

REPORT = ROOT / "docs" / "blocking_report.md"
RETRIEVERS = FLAGS + COSINES


def run_blocking(split: str, k: int, out: str, sample: int = 0) -> dict:
    cmd = [sys.executable, "-m", "src.blocking", split, "--k", str(k), "--out", out]
    if sample:
        cmd += ["--sample-records", str(sample)]
    res = subprocess.run(cmd, capture_output=True, text=True, cwd=ROOT)
    if res.returncode:
        raise RuntimeError(res.stderr)
    return json.loads(res.stdout.strip().splitlines()[-1])


def dev_truth() -> tuple[pd.DataFrame, dict[str, set[str]], list[str]]:
    dev_s1 = sorted(load_dev("s1"))
    gt = load_truth_df()
    gt = gt[gt["source1_entity_id"].isin(set(dev_s1))]
    truth = {s: set(filter(None, m.split(","))) for s, m in
             zip(gt["source1_entity_id"].tolist(), gt["matched_entity_ids"].tolist())}
    pairs = pd.DataFrame([(s, m) for s, ms in truth.items() for m in ms], columns=["s1_id", "cand_id"])
    country = pd.read_parquet(norm_path("dev", "source1"), columns=["entity_id", "country_norm"])
    pairs = pairs.merge(country.rename(columns={"entity_id": "s1_id", "country_norm": "country"}), on="s1_id")
    return pairs, truth, dev_s1


def evaluate(stats: dict, pairs: pd.DataFrame, truth: dict, dev_s1: list[str], n_pool: int) -> dict:
    c = pd.read_parquet(stats["out"], columns=["s1_id", "cand_id"] + RETRIEVERS)
    hit = pairs.merge(c, on=["s1_id", "cand_id"], how="left")
    found = hit["tfidf_name_cos"].notna()
    pred: dict[str, set[str]] = {}
    for s, m in zip(hit.loc[found, "s1_id"].tolist(), hit.loc[found, "cand_id"].tolist()):
        pred.setdefault(s, set()).add(m)
    row = {"k": stats["k"], "pair_recall": found.mean()}
    row.update({f"recall_{r}": (hit[r].fillna(0) > 0).mean() for r in RETRIEVERS})
    row.update({f"recall_{cty}": g.mean() for cty, g in found.groupby(hit["country"])})
    row.update({"f05_ceiling": macro_f05(pred, truth, dev_s1), "pairs": len(c),
                "cands_per_s1": len(c) / len(dev_s1), "cands_per_record": len(c) / n_pool})
    row.update({f"pairs_{r}": int((c[r] > 0).sum()) for r in RETRIEVERS})
    row.update({"runtime_s": stats["runtime_s"], "peak_mb": stats["peak_mb"]})
    return row


def extrapolate(stats: dict) -> dict:
    """Load and S1 index are paid in full during calibration; the rest scales with the record count."""
    st, ratio = stats["stages_s"], stats["n_rec_all"] / stats["n_rec"]
    fixed = st.get("load", 0) + st.get("s1_index", 0)
    variable = stats["runtime_s"] - fixed
    return {"split": stats["split"], "n_s1": stats["n_s1"], "records": stats["n_rec_all"],
            "sample": stats["n_rec"], "sample_runtime_s": stats["runtime_s"], "sample_peak_mb": stats["peak_mb"],
            "est_pairs": round(stats["pairs"] * ratio), "est_runtime_min": round((fixed + variable * ratio) / 60, 1),
            "stages_s": st}


def md_table(df: pd.DataFrame) -> str:
    def fmt(v) -> str:
        if isinstance(v, float):
            return f"{v:.4f}" if v <= 1 else f"{v:,.1f}"
        return f"{v:,}" if isinstance(v, int) else str(v)

    head = "| " + " | ".join(df.columns) + " |\n|" + "---|" * len(df.columns) + "\n"
    return head + "\n".join("| " + " | ".join(fmt(v) for v in r) + " |" for r in df.itertuples(index=False))


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--ks", type=int, nargs="+", default=[3, 5, 10])
    ap.add_argument("--calibrate-k", type=int)
    ap.add_argument("--sample", type=int, default=200_000)
    args = ap.parse_args()
    pairs, truth, dev_s1 = dev_truth()
    n_pool = len(load_dev("s2")) + len(load_dev("s3"))
    rows = []
    for k in args.ks:
        stats = run_blocking("dev", k, f"cands_dev_k{k}.parquet")
        rows.append(evaluate(stats, pairs, truth, dev_s1, n_pool))
        print(json.dumps(rows[-1]), json.dumps(stats["stages_s"]), flush=True)
    table = pd.DataFrame(rows)
    lines = ["# Blocking v1 report (generated by `python -m src.eval_blocking`)", "",
             f"Dev slice: {len(dev_s1):,} S1, {n_pool:,} S2/S3 records, {len(pairs):,} true pairs. "
             "The dev pool is LESS DENSE than real data (44k S1 instead of 1.7-2.2M compete for each record), "
             "so recall here is optimistic and candidates per S1 are inflated (26 records per S1 vs ~5).", "",
             "## Dev slice: recall, ceiling, volume", "", md_table(table[[c for c in table.columns
                                                                          if not c.startswith("pairs_")]]),
             "", "## Pairs contributed per retriever (a pair can come from several)", "",
             md_table(table[["k"] + [c for c in table.columns if c.startswith("pairs_")]])]
    if args.calibrate_k:
        lines += ["", f"## Full-scale estimate, k={args.calibrate_k} (calibration: {args.sample:,} random records "
                      "against the FULL S1 index; load + S1 index timed in full, the rest scaled)", ""]
        est = []
        for split in ("test", "train"):
            stats = run_blocking(split, args.calibrate_k, f"cands_{split}_calib.parquet", args.sample)
            est.append(extrapolate(stats))
            print(json.dumps(est[-1]), flush=True)
            (CACHE / f"cands_{split}_calib.parquet").unlink()
        lines.append(md_table(pd.DataFrame(est).drop(columns="stages_s")))
        lines += ["", "Stage seconds in calibration runs:", ""] + [f"- {e['split']}: {e['stages_s']}" for e in est]
    REPORT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
